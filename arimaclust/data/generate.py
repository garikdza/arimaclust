from typing import List, Tuple, Union
import statsmodels.api as sm
import numpy as np
from numpy.typing import ArrayLike
from arimaclust.data.examples import EXAMPLE1
from arimaclust.autoarima.estimation import to_arma_process, estimate_processes


def generate_arma_sample(ar_params: ArrayLike, ma_params: ArrayLike, t: int) -> np.ndarray:
    """
    Generate sample from ARMA process with given parameters

    Parameters
    ----------
    ar_params : ArrayLike
        autoregressive parameters
    ma_params : ArrayLike
        moving average parameters

    Returns
    -------
    x : np.ndarray
        time series
    """
    # get arma process
    x_process = to_arma_process(ar_params, ma_params)
    # generate sample
    x = x_process.generate_sample(nsample=t)
    return x


def generate_clusters(params: List[Tuple[ArrayLike]], t_min: int, samples_per_cluster: Union[int, list]) -> Tuple[
    List, List]:
    """
    Generate clustering dataset with given parameters.
    Each cluster is generated by one ARMA model.

    Parameters
    ----------
    params : List[Tuple[ArrayLike]]
        parameters of cluster generating processes
    t_min : int
        minimum t for each sample
    samples_per_cluster : Union[int,list]
        number of samples in each cluster

    Returns
    -------
    cluster_data, labels : Tuple[List, List]
        samples and labels
    """
    # each cluster generated with one process
    # params ex [(,),(,)]
    cluster_data = []
    labels = []
    for i, cluster_process_params in enumerate(params):
        if isinstance(samples_per_cluster, int):
            range_ = range(samples_per_cluster)
        elif isinstance(samples_per_cluster, list):
            range_ = range(samples_per_cluster[i])
        else:
            raise ValueError
        for j in range_:
            cluster_data.append(generate_arma_sample(*cluster_process_params, t=t_min))
            labels.append(i)
    return cluster_data, labels


